create or replace function public.create_unit_from_template(
  p_token text, p_city text, p_state text, p_franchisee text, p_opening_date date,
  p_owner_name text default null, p_priority text default 'Normal'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid;
  v_unit_id text;
  v_name text;
  v_tenant_id uuid;
begin
  v_user_id := public.require_platform_admin(p_token);
  v_unit_id := public.slugify(concat_ws('-', p_city, p_state));
  v_name := trim(concat(upper(p_city), ' ', upper(coalesce(p_state, ''))));
  if exists (select 1 from public.units where id = v_unit_id) then
    v_unit_id := v_unit_id || '-' || substr(encode(extensions.gen_random_bytes(3), 'hex'), 1, 6);
  end if;
  insert into public.tenants (code, name) values (v_unit_id, v_name) returning id into v_tenant_id;
  insert into public.units (id, tenant_id, name, city, state, franchisee, opening_date, source_file, owner_name, priority)
  values (v_unit_id, v_tenant_id, v_name, initcap(trim(p_city)), upper(trim(p_state)), p_franchisee, p_opening_date, 'Criado no sistema', p_owner_name, p_priority);
  insert into public.roadmap_tasks (id, unit_id, template_id, item, phase, process, status, sort_order)
  select v_unit_id || '-task-' || sort_order, v_unit_id, id, item, phase, process, 'Pendente', sort_order
  from public.roadmap_task_templates order by sort_order;
  insert into public.purchase_items (id, unit_id, template_id, item, status, sort_order)
  select v_unit_id || '-purchase-' || sort_order, v_unit_id, id, item, 'Pendente', sort_order
  from public.purchase_item_templates order by sort_order;
  insert into public.accreditation_units (id, name, owner_name)
  values (v_unit_id, upper(trim(p_city)), p_owner_name);
  insert into public.tenant_modules (tenant_id, module_code, status, enabled_at, enabled_by)
  select v_tenant_id, code, case when default_enabled then 'active' else 'locked' end,
         case when default_enabled then now() else null end,
         case when default_enabled then v_user_id else null end
  from public.module_catalog where active = true;
  insert into public.audit_events (user_id, entity_type, entity_id, action, payload)
  values (v_user_id, 'unit', v_unit_id, 'create_from_template', jsonb_build_object('tenantId', v_tenant_id, 'city', p_city, 'state', p_state));
  return jsonb_build_object('ok', true, 'unitId', v_unit_id, 'tenantId', v_tenant_id);
end;
$$;

create or replace function public.delete_franchise_unit(p_token text, p_unit_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid;
  v_tenant_id uuid;
begin
  v_user_id := public.require_platform_admin(p_token);
  select tenant_id into v_tenant_id from public.units where id = p_unit_id;
  delete from public.accreditation_statuses where unit_id = p_unit_id;
  delete from public.accreditation_units where id = p_unit_id;
