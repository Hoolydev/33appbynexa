create or replace function public.is_platform_admin(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.app_users u
    where u.id = p_user_id
      and u.active = true
      and lower(u.role) in ('admin', 'platform_admin')
  );
$$;

create or replace function public.can_access_tenant(p_user_id uuid, p_tenant_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_platform_admin(p_user_id) or exists (
    select 1
    from public.tenant_memberships tm
    join public.tenants t on t.id = tm.tenant_id
    where tm.user_id = p_user_id
      and tm.tenant_id = p_tenant_id
      and tm.active = true
      and t.status = 'active'
  );
$$;

create or replace function public.can_manage_tenant(p_user_id uuid, p_tenant_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
