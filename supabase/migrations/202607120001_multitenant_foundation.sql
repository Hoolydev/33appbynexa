create table if not exists public.tenants (
  id uuid primary key default extensions.gen_random_uuid(),
  code text not null unique,
  name text not null,
  status text not null default 'active' check (status in ('active', 'suspended', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.tenants enable row level security;

drop trigger if exists touch_tenants_updated_at on public.tenants;
create trigger touch_tenants_updated_at before update on public.tenants
for each row execute function public.touch_updated_at();

alter table public.units add column if not exists tenant_id uuid references public.tenants(id) on delete restrict;

insert into public.tenants (code, name)
select u.id, coalesce(nullif(u.name, ''), upper(u.city))
from public.units u
on conflict (code) do update set name = excluded.name;

update public.units u
set tenant_id = t.id
from public.tenants t
where t.code = u.id
  and u.tenant_id is null;

alter table public.units alter column tenant_id set not null;

create index if not exists units_tenant_id_idx on public.units(tenant_id);

create table if not exists public.tenant_memberships (
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid not null references public.app_users(id) on delete cascade,
  role text not null default 'user' check (role in ('franchise_admin', 'manager', 'user')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (tenant_id, user_id)
);

alter table public.tenant_memberships enable row level security;

drop trigger if exists touch_tenant_memberships_updated_at on public.tenant_memberships;
create trigger touch_tenant_memberships_updated_at before update on public.tenant_memberships
for each row execute function public.touch_updated_at();

create index if not exists tenant_memberships_user_id_idx on public.tenant_memberships(user_id);

