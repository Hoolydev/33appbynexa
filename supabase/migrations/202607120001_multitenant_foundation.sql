create or replace function public.admin_create_portal_user(
  p_token text,
  p_email text,
  p_name text,
  p_password text,
  p_tenant_id uuid default null,
  p_role text default 'user'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid;
  v_user_id uuid;
begin
  v_admin_id := public.require_platform_admin(p_token);
  if length(trim(coalesce(p_password, ''))) < 8 then
    raise exception 'A senha precisa ter pelo menos 8 caracteres' using errcode = '22023';
  end if;
  if p_role not in ('franchise_admin', 'manager', 'user') then
    raise exception 'Papel de franquia inválido' using errcode = '22023';
  end if;

  insert into public.app_users (email, name, password_hash, role, active)
  values (lower(trim(p_email)), trim(p_name), extensions.crypt(p_password, extensions.gen_salt('bf')), 'tenant_user', true)
  returning id into v_user_id;

  if p_tenant_id is not null then
    insert into public.tenant_memberships (tenant_id, user_id, role)
    values (p_tenant_id, v_user_id, p_role);
  end if;

  insert into public.audit_events (user_id, entity_type, entity_id, action, payload)
  values (v_admin_id, 'app_user', v_user_id::text, 'admin_create', jsonb_build_object('tenantId', p_tenant_id, 'role', p_role));

  return jsonb_build_object('ok', true, 'userId', v_user_id);
end;
$$;

