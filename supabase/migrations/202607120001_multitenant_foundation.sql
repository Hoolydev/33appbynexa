create or replace function public.admin_set_tenant_module(
  p_token text,
  p_tenant_id uuid,
  p_module_code text,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid;
begin
  v_admin_id := public.require_platform_admin(p_token);
  if p_status not in ('locked', 'requested', 'active', 'suspended') then
    raise exception 'Status de módulo inválido' using errcode = '22023';
  end if;
  insert into public.tenant_modules (tenant_id, module_code, status, enabled_at, enabled_by)
  values (p_tenant_id, p_module_code, p_status, case when p_status = 'active' then now() else null end, case when p_status = 'active' then v_admin_id else null end)
  on conflict (tenant_id, module_code) do update
    set status = excluded.status, enabled_at = excluded.enabled_at, enabled_by = excluded.enabled_by;
  if p_status = 'active' then
    update public.module_requests set status = 'approved', reviewed_by = v_admin_id, reviewed_at = now()
    where tenant_id = p_tenant_id and module_code = p_module_code and status = 'pending';
  end if;
  insert into public.audit_events (user_id, entity_type, entity_id, action, payload)
  values (v_admin_id, 'tenant_module', p_tenant_id::text || ':' || p_module_code, 'set_status', jsonb_build_object('status', p_status));
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.request_tenant_module(
  p_token text,
  p_tenant_id uuid,
  p_module_code text,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid;
  v_request_id bigint;
begin
  v_user_id := public.require_app_user(p_token);
  if not public.can_access_tenant(v_user_id, p_tenant_id) then
    raise exception 'Você não possui acesso a esta franquia' using errcode = '42501';
  end if;
  if p_module_code = 'business' then
    raise exception 'O módulo de Negócios já faz parte do plano padrão' using errcode = '22023';
  end if;
  if exists (select 1 from public.tenant_modules where tenant_id = p_tenant_id and module_code = p_module_code and status = 'active') then
    raise exception 'Este módulo já está ativo' using errcode = '22023';
  end if;
  insert into public.module_requests (tenant_id, module_code, requested_by, notes)
  select p_tenant_id, p_module_code, v_user_id, p_notes
  where not exists (
    select 1 from public.module_requests
    where tenant_id = p_tenant_id and module_code = p_module_code and status = 'pending'
  )
  returning id into v_request_id;
  update public.tenant_modules set status = 'requested'
  where tenant_id = p_tenant_id and module_code = p_module_code and status <> 'active';
  return jsonb_build_object('ok', true, 'requestId', v_request_id);
end;
$$;

