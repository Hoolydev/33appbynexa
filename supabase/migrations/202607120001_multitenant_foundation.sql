  tenant_id uuid not null references public.tenants(id) on delete cascade,
  module_code text not null references public.module_catalog(code) on delete restrict,
  status text not null default 'locked' check (status in ('locked', 'requested', 'active', 'suspended')),
  enabled_at timestamptz,
  enabled_by uuid references public.app_users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (tenant_id, module_code)
);

alter table public.tenant_modules enable row level security;

drop trigger if exists touch_tenant_modules_updated_at on public.tenant_modules;
create trigger touch_tenant_modules_updated_at before update on public.tenant_modules
for each row execute function public.touch_updated_at();

insert into public.tenant_modules (tenant_id, module_code, status, enabled_at)
select t.id, m.code, case when m.default_enabled then 'active' else 'locked' end,
       case when m.default_enabled then now() else null end
from public.tenants t
cross join public.module_catalog m
on conflict (tenant_id, module_code) do nothing;

