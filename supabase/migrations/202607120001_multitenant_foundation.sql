create or replace function public.require_platform_admin(p_token text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid;
begin
  v_user_id := public.require_app_user(p_token);
  if not public.is_platform_admin(v_user_id) then
    raise exception 'Acesso permitido somente para administradores da plataforma' using errcode = '42501';
  end if;
  return v_user_id;
end;
$$;

create or replace function public.require_unit_access(p_user_id uuid, p_unit_id text, p_manage boolean default false)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tenant_id uuid;
begin
  select tenant_id into v_tenant_id from public.units where id = p_unit_id;
  if v_tenant_id is null then
    raise exception 'Franquia não encontrada' using errcode = 'P0002';
  end if;
  if p_manage and not public.can_manage_tenant(p_user_id, v_tenant_id) then
    raise exception 'Você não possui permissão para alterar esta franquia' using errcode = '42501';
  elsif not p_manage and not public.can_access_tenant(p_user_id, v_tenant_id) then
    raise exception 'Você não possui acesso a esta franquia' using errcode = '42501';
  end if;
  return v_tenant_id;
end;
$$;

create or replace function public.get_portal_data(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid;
  v_is_admin boolean;
begin
  v_user_id := public.require_app_user(p_token);
  v_is_admin := public.is_platform_admin(v_user_id);

  return jsonb_build_object(
    'generatedAt', now(),
    'sourceFiles', coalesce((
      select jsonb_agg(distinct u.source_file)
      from public.units u
      where u.source_file is not null and (v_is_admin or public.can_access_tenant(v_user_id, u.tenant_id))
    ), '[]'::jsonb),
    'userProfile', coalesce((
      select jsonb_build_object(
        'name', coalesce(nullif(p.display_name, ''), nullif(u.name, ''), split_part(u.email, '@', 1), 'Usuário'),
        'photo', coalesce(p.photo_data, '')
      )
      from public.app_users u
      left join public.app_user_profiles p on p.user_id = u.id
      where u.id = v_user_id
    ), jsonb_build_object('name', 'Usuário', 'photo', '')),
    'accessContext', jsonb_build_object(
      'platformAdmin', v_is_admin,
      'memberships', coalesce((
        select jsonb_agg(jsonb_build_object(
          'tenantId', tm.tenant_id,
          'tenantName', t.name,
          'tenantCode', t.code,
          'role', tm.role,
          'permissions', coalesce((
            select jsonb_agg(jsonb_build_object(
              'moduleCode', mp.module_code,
              'canView', mp.can_view,
              'canEdit', mp.can_edit,
              'canApprove', mp.can_approve
            ) order by mp.module_code)
            from public.membership_module_permissions mp
            where mp.tenant_id = tm.tenant_id and mp.user_id = tm.user_id
          ), '[]'::jsonb)
        ) order by t.name)
        from public.tenant_memberships tm
        join public.tenants t on t.id = tm.tenant_id
        where tm.user_id = v_user_id and tm.active = true
      ), '[]'::jsonb)
    ),
    'tenantModules', coalesce((
      select jsonb_agg(jsonb_build_object(
        'tenantId', tm.tenant_id,
        'moduleCode', tm.module_code,
        'name', mc.name,
        'description', mc.description,
        'status', tm.status
      ) order by mc.sort_order, mc.name)
      from public.tenant_modules tm
      join public.module_catalog mc on mc.code = tm.module_code
      where mc.active = true and (v_is_admin or public.can_access_tenant(v_user_id, tm.tenant_id))
    ), '[]'::jsonb),
    'units', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', u.id,
        'tenantId', u.tenant_id,
        'name', u.name,
        'city', u.city,
        'state', coalesce(u.state, ''),
        'franchisee', coalesce(u.franchisee, ''),
        'openingDate', coalesce(u.opening_date::text, ''),
        'sourceFile', coalesce(u.source_file, ''),
        'ownerName', coalesce(u.owner_name, ''),
        'priority', coalesce(u.priority, 'Normal'),
        'tasks', coalesce((
          select jsonb_agg(jsonb_build_object(
            'id', r.id, 'item', coalesce(r.item, ''), 'phase', r.phase, 'process', r.process,
            'status', r.status, 'deadline', coalesce(r.deadline::text, ''),
            'actualDate', coalesce(r.actual_date::text, ''), 'notes', coalesce(r.notes, '')
          ) order by r.sort_order, r.item, r.process)
          from public.roadmap_tasks r where r.unit_id = u.id
        ), '[]'::jsonb),
        'purchases', coalesce((
          select jsonb_agg(jsonb_build_object(
            'id', p.id, 'item', p.item, 'status', p.status, 'notes', coalesce(p.notes, '')
          ) order by p.sort_order, p.item)
          from public.purchase_items p where p.unit_id = u.id
        ), '[]'::jsonb)
      ) order by u.city, u.state)
      from public.units u
      where v_is_admin or public.can_access_tenant(v_user_id, u.tenant_id)
    ), '[]'::jsonb),
    'operationalRecords', coalesce((
      select jsonb_agg(jsonb_build_object(
        'unitId', r.unit_id, 'recordType', r.record_type, 'recordId', r.record_id, 'hidden', r.hidden
      ) || r.payload order by r.updated_at desc)
      from public.unit_operational_records r
      join public.units u on u.id = r.unit_id
      where v_is_admin or public.can_access_tenant(v_user_id, u.tenant_id)
    ), '[]'::jsonb),
    'accreditation', jsonb_build_object(
      'sourceFile', 'Supabase',
      'units', coalesce((
        select jsonb_agg(jsonb_build_object('id', au.id, 'name', au.name, 'owner', coalesce(au.owner_name, '')) order by au.name)
        from public.accreditation_units au
        left join public.units u on u.id = au.id
        where v_is_admin or (u.id is not null and public.can_access_tenant(v_user_id, u.tenant_id))
      ), '[]'::jsonb),
      'procedures', coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', ap.id,
          'group', ap.group_name,
          'name', ap.name,
          'statuses', coalesce((
            select jsonb_object_agg(acs.unit_id, acs.status)
            from public.accreditation_statuses acs
            left join public.units u on u.id = acs.unit_id
            where acs.procedure_id = ap.id
              and not coalesce(acs.hidden, false)
              and (v_is_admin or (u.id is not null and public.can_access_tenant(v_user_id, u.tenant_id)))
          ), '{}'::jsonb),
          'details', coalesce((
            select jsonb_object_agg(acs.unit_id, jsonb_build_object(
              'status', acs.status,
              'requestDate', coalesce(acs.request_date::text, ''),
              'approvalDate', coalesce(acs.approval_date::text, ''),
              'owner', coalesce(acs.owner_name, ''),
              'attachments', coalesce(acs.attachments, ''),
              'notes', coalesce(acs.notes, ''),
              'hidden', coalesce(acs.hidden, false)
            ))
            from public.accreditation_statuses acs
            left join public.units u on u.id = acs.unit_id
            where acs.procedure_id = ap.id
              and (v_is_admin or (u.id is not null and public.can_access_tenant(v_user_id, u.tenant_id)))
          ), '{}'::jsonb)
        ) order by ap.sort_order, ap.name)
        from public.accreditation_procedures ap
      ), '[]'::jsonb)
    ),
    'modelTasks', coalesce((
      select jsonb_agg(jsonb_build_object('phase', phase, 'item', coalesce(item, ''), 'process', process) order by sort_order)
      from public.roadmap_task_templates
    ), '[]'::jsonb),
    'purchaseItems', coalesce((select jsonb_agg(item order by sort_order, item) from public.purchase_item_templates), '[]'::jsonb),
    'admin', case when v_is_admin then jsonb_build_object(
      'tenants', coalesce((
        select jsonb_agg(jsonb_build_object('id', t.id, 'code', t.code, 'name', t.name, 'status', t.status) order by t.name)
        from public.tenants t
      ), '[]'::jsonb),
      'users', coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', u.id, 'name', u.name, 'email', u.email, 'platformRole', u.role, 'active', u.active,
          'memberships', coalesce((
            select jsonb_agg(jsonb_build_object('tenantId', tm.tenant_id, 'tenantName', t.name, 'role', tm.role, 'active', tm.active) order by t.name)
            from public.tenant_memberships tm join public.tenants t on t.id = tm.tenant_id where tm.user_id = u.id
          ), '[]'::jsonb)
        ) order by u.name, u.email)
        from public.app_users u
      ), '[]'::jsonb),
      'requests', coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', mr.id, 'tenantId', mr.tenant_id, 'tenantName', t.name, 'moduleCode', mr.module_code,
          'moduleName', mc.name, 'status', mr.status, 'notes', coalesce(mr.notes, ''),
          'requestedBy', u.name, 'createdAt', mr.created_at
        ) order by mr.created_at desc)
        from public.module_requests mr
        join public.tenants t on t.id = mr.tenant_id
        join public.module_catalog mc on mc.code = mr.module_code
        join public.app_users u on u.id = mr.requested_by
      ), '[]'::jsonb)
    ) else null end
  );
end;
$$;

